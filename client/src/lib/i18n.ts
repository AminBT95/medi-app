export type TranslationKey = keyof typeof translations.fr;
export type Language = keyof typeof translations;

export function translate(key: TranslationKey, language: Language, variables?: Record<string, string | number>): string {
  let text = translations[language][key] || translations.fr[key] || key;
  
  if (variables) {
    Object.entries(variables).forEach(([varKey, value]) => {
      text = text.replace(`{${varKey}}`, String(value));
    });
  }
  
  return text;
}
